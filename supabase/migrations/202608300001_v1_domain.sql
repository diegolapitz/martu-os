create table if not exists public.content_workflows (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public.clients(id) on delete cascade,
  name text not null,
  slug text not null,
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint content_workflows_client_slug_unique unique (client_id, slug),
  constraint content_workflows_name_not_blank check (btrim(name) <> ''),
  constraint content_workflows_slug_not_blank check (btrim(slug) <> '')
);

create unique index if not exists content_workflows_one_default_idx
  on public.content_workflows (client_id) where is_default;

create table if not exists public.content_workflow_states (
  id bigint generated by default as identity primary key,
  workflow_id bigint not null references public.content_workflows(id) on delete cascade,
  slug text not null,
  label text not null,
  color text not null default '#64748b',
  position integer not null default 0,
  is_visible boolean not null default true,
  terminal_kind text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint content_workflow_states_workflow_slug_unique unique (workflow_id, slug),
  constraint content_workflow_states_label_not_blank check (btrim(label) <> ''),
  constraint content_workflow_states_terminal_valid check (terminal_kind is null or terminal_kind in ('delivered','published','cancelled'))
