create table if not exists public.script_counters (
  client_id bigint primary key references public.clients(id) on delete cascade,
  next_number integer not null default 1,
  constraint script_counters_next_positive check (next_number > 0)
);

insert into public.script_counters (client_id, next_number)
select c.id, coalesce(max(s.script_number), 0) + 1
from public.clients c left join public.scripts s on s.client_id = c.id
group by c.id
on conflict (client_id) do update set next_number = greatest(public.script_counters.next_number, excluded.next_number);

